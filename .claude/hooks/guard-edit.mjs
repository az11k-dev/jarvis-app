#!/usr/bin/env node
// PreToolUse(Edit|Write): keep edits out of generated native folders (CNG).
import { readFileSync } from 'node:fs';
import { relative } from 'node:path';

const input = JSON.parse(readFileSync(0, 'utf8') || '{}');
const root = process.env.CLAUDE_PROJECT_DIR || input.cwd || process.cwd();
const file = input.tool_input?.file_path ?? '';
const rel = relative(root, file);

const block = (why) => {
  process.stderr.write(`Blocked by project hook: ${why}\n`);
  process.exit(2);
};

if (/^(android|ios)\//.test(rel))
  block(
    `${rel} is generated by \`expo prebuild\` (CNG) and gets overwritten. Put the change in app.config.js, a config plugin or a local module under modules/.`
  );
